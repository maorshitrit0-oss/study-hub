import json
import math
from pathlib import Path

Q = []
lin = lambda d: 10 ** (d / 10)  # noqa: E731


def q(title, question, solution):
    Q.append({"add": True, "free": True, "source": "exam", "title": "🎯 שאלה צפויה: " + title, "question_md": question,
              "solution_md": solution, "exam_style": True, "uncertain": False})


L = lin(6)
FA = L + (lin(2) - 1) * L + (lin(10) - 1) * L / lin(20)
FB = lin(2) + (L - 1) / lin(20) + (lin(10) - 1) * L / lin(20)
assert abs(10 * math.log10(FA) - 8.24) < 0.01 and abs(10 * math.log10(FB) - 2.95) < 0.01
q("איפה לשים את המגבר הרגיש – לפני הכבל או אחריו",
  r"""(כמו שרשרת המנחתים והמגברים מהכיתה.) מקלט עם ספרת רחש $10\,dB$. בין האנטנה למקלט יש כבל עם הפסד $6\,dB$, ויש מגבר רגיש עם הגבר $20\,dB$ וספרת רחש $2\,dB$.

1. ספרת הרחש הכוללת כשהמגבר **אחרי** הכבל (ליד המקלט).
2. ספרת הרחש הכוללת כשהמגבר **לפני** הכבל (ליד האנטנה).
3. **הקאץ':** כמה דציבלים הרווחנו, ולמה?""",
  r"""**בליניארי:** כבל $L=3.98$ (גם ספרת הרחש שלו, וההגבר $1/L=0.251$); מגבר $g=100$, $F=1.585$; מקלט $F=10$.

### 1. כבל ← מגבר ← מקלט
**נוסחה (פריס):** $$F=F_1+\frac{F_2-1}{g_1}+\frac{F_3-1}{g_1g_2}$$
**הצבה:** $$F=3.98+\frac{0.585}{0.251}+\frac{9}{0.251\cdot100}=3.98+2.33+0.36$$
**תוצאה:** $$F\approx6.67\;\Rightarrow\;8.2\,dB$$ ✅

### 2. מגבר ← כבל ← מקלט
**הצבה:** $$F=1.585+\frac{3.98-1}{100}+\frac{9}{100\cdot0.251}=1.585+0.030+0.36$$
**תוצאה:** $$F\approx1.97\;\Rightarrow\;3.0\,dB$$ ✅

### 3. הקאץ'
רווחנו כ-$5.3\,dB$. הדרגה **הראשונה** קובעת: כבל ראשון "מוסיף" את כל ה-$6\,dB$ שלו לפני שיש הגבר שיסתיר אותם. מגבר רגיש ראשון ⇐ כל מה שאחריו מחולק ב-100.

💡 **הרעיון:** בפריס כל דרגה מחולקת בהגבר של **כל** מה שלפניה. לכן: המגבר הרגיש – כמה שיותר קרוב לאנטנה.""")

mds = -174 + 10 * math.log10(200e3) + 6 + 12
d1 = 10 ** ((20 - mds - 20 * math.log10(9e8) - 20 * math.log10(4 * math.pi / 3e8)) / 20)
assert abs(mds + 103.0) < 0.02 and abs(d1 / 1e3 - 37.4) < 0.05
q("סף רגישות וטווח קשר",
  r"""(כמו תכנון הערוץ מהתרגול, בחלל חופשי.) מקלט: רוחב סרט $200\,kHz$, ספרת רחש $6\,dB$, דרוש יחס אות לרעש $12\,dB$. משדר $20\,dBm$ בתדר $900\,MHz$, אנטנות איזוטרופיות.

1. מה סף הרגישות?
2. מה הטווח המרבי?
3. **הקאץ':** הדרישה עולה ל-$18\,dB$. מה הטווח עכשיו?""",
  r"""### 1. סף רגישות
**נוסחה:** $$MDS=-174+10\log_{10}B+F+SNR$$
**הצבה:** $$MDS=-174+53.0+6+12$$
**תוצאה:** $$MDS\approx-103\,dBm$$ ✅

### 2. טווח
$$FSPL_{max}=P_t-MDS=20-(-103)=123\,dB$$
$$20\log_{10}d=123-20\log_{10}(9\cdot10^8)-20\log_{10}\frac{4\pi}{c}=123-179.08+147.56=91.48$$
$$d\approx37.4\,km$$ ✅

### 3. הקאץ'
עוד $6\,dB$ בדרישה ⇐ $FSPL$ מותר קטן ב-$6\,dB$ ⇐ הטווח **חצי**: $d\approx18.8\,km$ ✅ (כל $6\,dB$ = פי 2 במרחק, כי $FSPL\propto20\log d$).

💡 **הרעיון:** $-174\,dBm/Hz$ = רעש תרמי ב-$290\,K$. סף = רעש + ספרת רחש + SNR. טווח = מתי $P_t-FSPL$ יורד לסף.""")

assert abs(10 * math.log10(0.25 / (1e-9 * 1e3)) - 53.98) < 0.01
q("אפנון DSB-SC וגילוי קוהרנטי – שגיאת פאזה ושגיאת תדר",
  r"""(כמו התרגיל מהכיתה בהרצאה 4.) $x(t)=2\cos(2\pi\cdot1000t)$ מאופנן ב-DSB-SC על נושא $100\,kHz$. רעש לבן $N_0=10^{-9}\,W/Hz$, אין ניחות בערוץ.

1. רוחב הסרט והספק השידור.
2. יחס אות לרעש במוצא בסנכרון מלא, ועם שגיאת פאזה $\theta=60^\circ$.
3. **הקאץ':** למתנד המקומי יש שגיאת **תדר** של $10\,Hz$ (בלי שגיאת פאזה). מה יוצא במוצא?""",
  r"""### 1. רוחב סרט והספק
$f_m=1\,kHz$ ⇐ $BW=2f_m=2\,kHz$ ✅
$$P_x=\frac{2^2}2=2\,W,\qquad P_{DSB}=\frac{P_x}2=1\,W$$ ✅

### 2. יחס אות לרעש (אותה נוסחה כמו בכיתה)
$$SNR_{out}=\frac{P_{in}}{N_0B}\cos^2\theta$$
- $\theta=0$: $$\frac{1}{10^{-9}\cdot10^3}=10^6\;\Rightarrow\;60\,dB$$ ✅
- $\theta=60^\circ$: $\cos^2=0.25$ ⇐ $$2.5\cdot10^5\;\Rightarrow\;54\,dB$$ ✅ (הפסד של $6\,dB$)

### 3. הקאץ' – שגיאת תדר
המוצא אחרי המסנן: $$\tfrac12x(t)\cos(2\pi\cdot10\,t)$$ ✅
האות "נושם": המשרעת עולה ויורדת 20 פעמים בשנייה ועוברת דרך אפס – זה **לא** הפסד קבוע כמו בשגיאת פאזה, אלא עיוות. לכן במקלט DSB-SC חייבים סנכרון גם בתדר וגם בפאזה.

💡 **הרעיון:** שגיאת פאזה ⇐ הנחתה קבועה $\cos\theta$; שגיאת תדר ⇐ כפל ב-$\cos(2\pi\Delta f\,t)$ שמשתנה בזמן.""")

