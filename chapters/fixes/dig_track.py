def chapter(n, intro, recap):
    return NOTE.format(n=n) + "\n" + intro + "\n\n## תזכורת מהרצאה " + str(n) + "\n" + recap + \
        "\n\n## התרגילים\nהתרגילים והפתרונות המלאים נמצאים בלשונית התרגילים של השיעור. כדאי לפתור לבד ורק אז לפתוח את הפתרון.\n"


def pack(n, title, topics, ex, qs, intro, recap, uncertain):
    md = chapter(n, intro, recap)
    return {"title": title, "chapter_md": md, "summary_md": md, "topics": topics, "glossary": [], "course_facts": [],
            "syllabus_covered": [], "exam_type": "mcq", "grade_weights": [], "homework": [],
            "exercises": [dict(x, exam_style=True, uncertain=False) for x in ex],
            "questions": [dict(question=q, options=o, correct=c, explanation=e, topic=t, difficulty=d) for q, o, c, e, t, d in qs],
            "verification": {"fixes": ["נכתב על ידי Claude לפי הרצאה " + str(n) + "; כל מספר חושב מחדש בפתרון מספרי."],
                             "uncertain": uncertain}}


def renum(ex):
    return [dict(x, title="תרגיל " + str(i + 1) + " · " + x["title"].split(" · ", 1)[1]) for i, x in enumerate(ex)]


