def pack(qs, seed):
    rnd = random.Random(seed)
    out = []
    for q in qs:
        opts = [q["right"]] + q["wrong"]
        rnd.shuffle(opts)
        out.append({"question": q["question"], "options": opts, "correct": opts.index(q["right"]), "explanation": q["explanation"],
                    "topic": q["topic"], "difficulty": q["difficulty"]})
    return out


