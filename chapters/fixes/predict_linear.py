q("מעגל מגברי שרת רב-דרגתי עם משוב גלובלי – הגבר והתנגדות מבוא",
  r"""אותו מבנה כמו בתרגול 3 (שני מגברים מהפכים ונגד משוב מהמוצא לכניסה), נתונים אחרים: נגד כניסה $10\,k\Omega$ להדק $-$ של המגבר הראשון, משוב $20\,k\Omega$ במגבר הראשון; המגבר השני מהפך עם $40\,k\Omega$ ו-$40\,k\Omega$; נגד $R_F=40\,k\Omega$ מהמוצא **ישר לכניסה** $V_{in}$. ההדקים $+$ באדמה, מגברים אידיאליים.

1. מצא $A_v=V_{out}/V_{in}$.
2. מצא $R_{in}$.
3. **הקאץ':** מה $R_{in}$ אם $R_F=5\,k\Omega$? מה המשמעות?""",
  r"""### 1. הגבר
מגבר 1 (מהפך): $$V_x=-\frac{20}{10}V_{in}=-2V_{in}$$
מגבר 2 (מהפך, $40/40$): $$V_{out}=-V_x=2V_{in}\;\Rightarrow\;A_v=2$$ ✅
$R_F$ מחובר לכניסה ולא להדק $-$, ולכן **לא משנה את ההגבר**.

### 2. התנגדות מבוא
מהמקור יוצאים שני זרמים: לאדמה המדומה ודרך $R_F$ למוצא:
$$I_{in}=\frac{V_{in}}{10\,k}+\frac{V_{in}-2V_{in}}{40\,k}=V_{in}\left(\frac1{10\,k}-\frac1{40\,k}\right)=\frac{3V_{in}}{40\,k}$$
$$R_{in}=\frac{40\,k}{3}\approx13.3\,k\Omega$$ ✅ (יותר מ-$10\,k\Omega$: המשוב מחזיר חלק מהזרם)

### 3. הקאץ' – $R_F=5\,k\Omega$
$$I_{in}=\frac{V_{in}}{10\,k}-\frac{V_{in}}{5\,k}=-\frac{V_{in}}{10\,k}\;\Rightarrow\;R_{in}=-10\,k\Omega$$ ✅
**התנגדות שלילית:** המעגל **מחזיר** זרם למקור. (בתרגול, עם $R_F=20\,k\Omega$ והגבר 3, יצא בדיוק אינסוף.) באופן כללי: $\frac1{R_{in}}=\frac1{R}+\frac{1-A_v}{R_F}$.

💡 **הרעיון:** הגבר – שרשרת מהפכים. התנגדות מבוא – KCL בצומת הכניסה עם **כל** הנגדים שמחוברים אליו.""")

H = -10 / (1 + 10j)
