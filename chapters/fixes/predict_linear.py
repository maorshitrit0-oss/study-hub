q("מגבר פולט משותף בפרמטרי h – הגבר עם מקור ועומס",
  r"""טרנזיסטור עם $h_{ie}=2\,k\Omega$, $h_{fe}=100$, $h_{re}\approx0$. מגבר פולט משותף: $R_C=4\,k\Omega$, עומס $R_L=4\,k\Omega$, מקור עם $R_s=1\,k\Omega$.

1. בהזנחת $h_{oe}$: מה $v_o/v_b$ ומה $v_o/v_s$?
2. **הקאץ':** $h_{oe}=25\,\mu S$. כמה משתנה ההגבר?""",
  r"""### 1. בלי $h_{oe}$
$$\frac{v_o}{v_b}=-h_{fe}\frac{R_C\parallel R_L}{h_{ie}}=-100\cdot\frac{2\,k}{2\,k}=-100$$ ✅
מחלק מתח בכניסה: $$\frac{v_b}{v_s}=\frac{h_{ie}}{R_s+h_{ie}}=\frac23$$
$$\frac{v_o}{v_s}=-100\cdot\frac23\approx-66.7$$ ✅

### 2. עם $h_{oe}$
$1/h_{oe}=40\,k\Omega$ במקביל במוצא:
$$R_C\parallel R_L\parallel40\,k=2\,k\parallel40\,k\approx1.905\,k\Omega$$
$$\frac{v_o}{v_b}=-100\cdot\frac{1.905}{2}\approx-95.2,\qquad\frac{v_o}{v_s}\approx-63.5$$ ✅
ירידה של כ-5%.

**הקאץ':** שכחת את $R_s$ ⇐ טעות של שליש. שכחת את $h_{oe}$ ⇐ טעות של 5%. במבחן מבקשים בדרך כלל את $v_o/v_s$.

💡 **הרעיון:** הגבר = $-h_{fe}\cdot$(כל מה שבמוצא במקביל)$/h_{ie}$, ואחר כך מחלק המתח של המקור.""")

