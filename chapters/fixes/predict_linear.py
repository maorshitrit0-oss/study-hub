assert abs(1 / (2 * math.pi * 100e3 * 1e3) - 1.5915e-9) < 1e-12
q("תכנון מסנן מעביר נמוכים פעיל – רכיבים, ותגובה בתדר גבוה",
  r"""מתכננים מסנן מעביר נמוכים פעיל (מגבר מהפך, $R_2\parallel C$ במשוב) כמו בתרגול 3: הגבר $20\,dB$ בתדרים נמוכים, תדר חיתוך $1\,kHz$, התנגדות מבוא $10\,k\Omega$.

1. מצא $R_1$, $R_2$, $C$.
2. כתוב את $H(j\omega)$.
3. **הקאץ':** מה ההגבר (בדציבלים) והפאזה ב-$10\,kHz$?""",
  r"""### 1. רכיבים
- התנגדות מבוא של מהפך = $R_1$ ⇐ $R_1=10\,k\Omega$ ✅
- $20\,dB$ ⇐ $|R_2/R_1|=10$ ⇐ $R_2=100\,k\Omega$ ✅
- **נוסחה:** $$f_c=\frac1{2\pi R_2C}\;\Rightarrow\;C=\frac1{2\pi\cdot100\,k\cdot1\,k}\approx1.59\,nF$$ ✅

### 2. פונקציית תמסורת
$$H(j\omega)=-\frac{R_2}{R_1}\cdot\frac1{1+j\omega R_2C}=\frac{-10}{1+j\,f/1\,kHz}$$ ✅

### 3. ב-$10\,kHz$
$$H=\frac{-10}{1+j10},\quad|H|=\frac{10}{\sqrt{101}}\approx0.995\;\Rightarrow\;\approx-0.04\,dB$$ ✅
הפאזה: $180^\circ$ מהמהפך פחות $\arctan10=84.3^\circ$ ⇐ $\approx95.7^\circ$ ✅

**הקאץ':** עשור אחרי החיתוך ההגבר ירד ב-$20\,dB$ – מ-$20\,dB$ ל-$\approx0\,dB$, ולא לאפס. ואל תשכח את ה-$180^\circ$ של המהפך.

💡 **הרעיון:** $R_1$ = התנגדות מבוא, $R_2/R_1$ = הגבר, $R_2C$ = תדר חיתוך. מסדר ראשון: $-20\,dB$ לעשור.""")

ACL = -100 / (1 + 101 / 1000)
assert abs(ACL + 90.83) < 0.01
q("מגבר מהפך עם הגבר חוג פתוח סופי – שגיאה ותכנון",
  r"""מגבר מהפך: $R_1=1\,k\Omega$, $R_2=100\,k\Omega$, הגבר חוג פתוח $A=1000$.

1. מה ההגבר האידיאלי ומה ההגבר האמיתי?
2. מה השגיאה באחוזים?
3. **הקאץ':** מה ה-$A$ המינימלי כדי שהשגיאה תהיה קטנה מ-$1\%$?""",
  r"""### 1. הגבר
אידיאלי: $$-\frac{R_2}{R_1}=-100$$
אמיתי (הנוסחה מהכיתה):
$$A_{CL}=-\frac{R_2/R_1}{1+\frac{1+R_2/R_1}{A}}=-\frac{100}{1+\frac{101}{1000}}\approx-90.8$$ ✅

### 2. שגיאה
$$\frac{100-90.8}{100}\approx9.2\%$$ ✅

### 3. $A$ מינימלי
$$\frac1{1+101/A}\ge0.99\;\Rightarrow\;\frac{101}{A}\le\frac1{99}\;\Rightarrow\;A\ge9999\approx10^4$$ ✅

**הקאץ':** הגבר 1000 נשמע "אינסופי", אבל עם הגבר רצוי של 100 נשארת שגיאה של 9%. מה שקובע הוא היחס $A/(1+R_2/R_1)$.

💡 **הרעיון:** השגיאה היחסית $\approx(1+R_2/R_1)/A$. ככל שמבקשים הגבר גבוה יותר – צריך $A$ גבוה יותר.""")

Av = -100 * (1 / (1 / 4e3 + 1 / 4e3 + 1 / 40e3)) / 2e3
