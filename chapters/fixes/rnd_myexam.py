add("המבחן שלי (מועד ב' 26/10) שאלה 4 - משערך לינארי עם משתנים רציפים", r"""
$X\sim U[-1,1]$ (אחיד), $N\sim\text{Exp}(3)$ (צפיפות $3e^{-3n}$, $n\ge0$), בלתי תלויים, ו-$Y=X-N$.
נתון: $\int_0^\infty xe^{-ax}dx=\frac1{a^2}$, $\int_0^\infty x^2e^{-ax}dx=\frac2{a^3}$, ושונות אחיד $\frac{(b-a)^2}{12}$.
1. חשב/י $E[Y]$ ו-$\mathrm{Var}(Y)$.
2. מצא/י את המשערך הלינארי האופטימלי של $X$ בהינתן $Y$, ואת השגיאה.
(אצלך: 3/10 – "המשתנים רציפים, לא בדידים", ו-8/10 על הנוסחה.)""", r"""
### ⚠️ הטעות המרכזית שלך
חישבת $E[X]=1\cdot\frac12+0\cdot\dots+(-1)\cdot\frac12$ – כאילו $X$ מקבל ערכים בדידים. נתונה **צפיפות** ⇐ המשתנים **רציפים** ⇐ מחשבים עם **אינטגרלים** (או עם הנוסחאות המוכנות של הפילוג).

### סעיף 1: מומנטים
**$X\sim U[-1,1]$:**
$$E[X]=\frac{-1+1}2=0,\qquad \mathrm{Var}X=\frac{(1-(-1))^2}{12}=\frac4{12}=\frac13$$
**$N\sim\text{Exp}(3)$** – עם האינטגרלים הנתונים, **לא לשכוח את ה-3 שבצפיפות**:
$$E[N]=\int_0^\infty n\cdot3e^{-3n}dn=3\cdot\frac1{3^2}=\frac13$$
$$E[N^2]=3\cdot\frac2{3^3}=\frac29,\qquad \mathrm{Var}N=\frac29-\frac19=\frac19$$
(⚠️ אצלך יצא $\frac19$ לתוחלת – בלי הכפל ב-3.)
**$Y=X-N$** (בלתי תלויים, אז השונויות מתחברות גם בחיסור):
$$E[Y]=0-\tfrac13=\boxed{-\tfrac13},\qquad \mathrm{Var}Y=\tfrac13+\tfrac19=\boxed{\tfrac49}$$

### סעיף 2: LMMSE
$$\hat X=E[X]+\frac{\mathrm{Cov}(X,Y)}{\mathrm{Var}Y}(Y-E[Y])$$
$$\mathrm{Cov}(X,Y)=\mathrm{Cov}(X,X-N)=\mathrm{Var}X-\underbrace{\mathrm{Cov}(X,N)}_{0}=\frac13$$
$$\hat X=0+\frac{1/3}{4/9}\left(Y+\frac13\right)=\boxed{\frac34\left(Y+\frac13\right)=\frac34Y+\frac14}$$
**השגיאה:**
$$E[(X-\hat X)^2]=\mathrm{Var}X-\frac{\mathrm{Cov}^2}{\mathrm{Var}Y}=\frac13-\frac{1/9}{4/9}=\frac13-\frac14=\boxed{\frac1{12}}$$
(השגיאה ירדה מ-$\frac13$ ל-$\frac1{12}$ – פי 4.)

> ⚠️ הנתונים המדויקים ($Y=X-N$, הפרמטר 3, $X$ על $[-1,1]$) שוחזרו מהחישובים שבמחברת. אם בטופס היה $Y=X+N$ – הכל זהה חוץ מ-$E[Y]=+\frac13$ ו-$\hat X=\frac34(Y-\frac13)$.

💡 **הרעיון:** LMMSE = 4 מספרים ($E[X],E[Y],\mathrm{Var}Y,\mathrm{Cov}$) ונוסחה אחת. עם $Y=X\pm N$ בלתי תלויים: $\mathrm{Cov}(X,Y)=\mathrm{Var}X$ תמיד.
""", "שערוך MMSE", uncertain=True)

