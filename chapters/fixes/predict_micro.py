q("כפתור עם INPUT_PULLUP – מה קורה בלחיצה אחת (קוד להבנה)",
  r"""כפתור מחובר בין GPIO 4 לאדמה:
```cpp
const int BTN = 4, LED = 2;
int count = 0, last = HIGH;

void setup() {
  pinMode(BTN, INPUT_PULLUP);
  pinMode(LED, OUTPUT);
  Serial.begin(115200);
}

void loop() {
  int now = digitalRead(BTN);
  if (last == HIGH && now == LOW) {
    count++;
    digitalWrite(LED, count % 2);
    Serial.println(count);
  }
  last = now;
}
```
1. מה יודפס ומה מצב הנורית אחרי לחיצה **אחת נקייה** ושחרור?
2. הכפתור "מקפץ" 3 פעמים בלחיצה. מה יודפס עכשיו ומה מצב הנורית?
3. **הקאץ':** מחליפים ל-`pinMode(BTN, INPUT)` בלי נגד חיצוני. מה יקרה?""",
  r"""**1. לחיצה נקייה.** משוחרר = HIGH (הנגד הפנימי מושך למעלה), לחוץ = LOW.
המעבר `HIGH ← LOW` קורה פעם אחת ⇐ `count = 1`, מודפס `1`, הנורית `1 % 2 = 1` ⇐ **דולקת**. בשחרור (LOW←HIGH) התנאי לא מתקיים ⇐ כלום. ✅

**2. שלוש קפיצות.** כל קפיצה היא עוד מעבר HIGH←LOW ⇐ הקוד סופר **3**: מודפס `1`, `2`, `3`, והנורית $3\%2=1$ ⇐ דולקת. במקרה של 2 קפיצות היא הייתה **כבויה** – התוצאה תלויה במזל. ✅
**התיקון:** debounce עם `millis()` – לקבל מצב חדש רק אם הוא יציב 20 ms (כמו בתרגיל מהכיתה).

**3. `INPUT` בלי נגד.** כשהכפתור משוחרר הפין **צף** – לא מחובר לשום מתח, והקריאה אקראית (רעש, אצבע ליד). הקוד יספור "לחיצות" בלי שנגעו בכפתור. ✅

💡 **הרעיון:** כפתור לאדמה + `INPUT_PULLUP` ⇐ לחוץ = LOW. מזהים **מעבר** (last מול now), לא מצב – ובלי debounce מעבר אחד נספר כמה פעמים.""")

